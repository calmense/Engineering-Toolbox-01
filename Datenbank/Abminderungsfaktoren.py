def calc_phi(lambda_bar, alpha):
    return 0.5 * (
        1
        + alpha * (lambda_bar - 0.2)
        + lambda_bar**2
    )


def calc_chi(lambda_bar, knicklinie):
    alpha = ABMINDERUNGSFAKTOREN_CHI[knicklinie]

    phi = calc_phi(
        lambda_bar,
        alpha,
    )

    chi = 1.0 / (
        phi
        + math.sqrt(
            phi**2 - lambda_bar**2
        )
    )

    return min(1.0, chi)